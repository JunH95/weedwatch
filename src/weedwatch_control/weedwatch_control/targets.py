#!/usr/bin/env python3
"""표적 계획의 **재관측 매칭** — 순수 함수 (시뮬·ROS 불요).

왜 따로 빼나: 이 규칙이 코디네이터의 주행 루프 안에 박혀 있어서 단위로 검증할 수 없었고,
그 상태에서 실제로 물렸다 — 옆 잡초를 같은 것으로 오인해 표적이 계속 앞으로 도망갔고,
그 툴이 막혀 **두둑 하나를 통째로 놓쳤다**(개발 밭 실측: 검출 7 · 타격 0).

── 무엇을 푸는 규칙인가 ────────────────────────────────────────────────────
잡초를 **처음 본 순간에 고정하지 않는다**. 검출은 로봇의 현재 추정 자세 기준 world 좌표라,
다시 볼 때마다 그때까지 쌓인 위치오차가 리셋된다. 그래서 죽은 추측 구간이
"처음 보인 곳→툴"(64~100cm)에서 "마지막으로 보인 곳→툴"(15~51cm)로 줄고,
개발 밭에서 평균 타격오차가 22.07 → 10.17cm 로 떨어진다(`make lead`).

그 대가로 **오인**이 생긴다. 그래서 두 조건을 같이 건다:
  1. 거리    — 같은 잡초로 볼 만큼 가까운가 (MATCH_R)
  2. **방향** — 갱신이 표적을 진행 반대로 밀어내지 않는가 (RECEDE_TOL)
다가가는 중인 표적이 갑자기 멀어지면 그건 같은 잡초가 아니라 **다음 잡초**다.
"""
from __future__ import annotations

import math

# 같은 잡초의 재관측으로 볼 거리 [m]. 5Hz·0.2m/s 면 프레임 간 4cm 이동이라 넉넉하고,
# 두 잡초를 한 개로 합쳐버릴 만큼 크지는 않다(예전 격자 키가 6cm 였다).
MATCH_R = 0.10

# 재관측이 표적을 진행 반대로 밀어낼 수 있는 한도 [m]. 검출 잡음만큼은 허용하되,
# 옆 잡초로 갈아타는 것(실측 간격 13~19cm)은 막는다.
RECEDE_TOL = 0.05

# 표적을 잡은 뒤 이만큼 갔는데도 못 쳤으면 포기한다 [m]. 툴 하나가 막혀 나머지를 다 놓치는 걸
# 막는 마지막 안전망 — 가장 뒤 툴의 리드(0.51m)보다 넉넉히 크게.
STUCK_M = 1.0

# 계획의 단계. 4(포기)는 안전망이 놓아준 것 — 놓친 이유를 사후에 가르기 위해 남긴다.
PENDING, AIMING, STRUCK, DONE, ABANDONED = 0, 1, 2, 3, 4


def match(pool, wx, wy, strike_x, ox, d):
    """pool 안에서 (wx, wy) 를 **같은 잡초의 재관측**으로 볼 계획을 고른다. 없으면 None.

    pool      : 이 툴이 맡은 계획들 (dict: wx, wy, strike_x, phase)
    wx, wy    : 새 검출의 world 좌표
    strike_x  : 그 검출로 계산한 타격 지점 (base x)
    ox        : 지금 추정 위치 (base x)
    d         : 진행 방향 (+1 / -1)
    """
    for p in pool:
        if p["phase"] >= STRUCK:                     # 이미 친 표적은 건드리지 않는다
            continue
        if math.hypot(p["wx"] - wx, p["wy"] - wy) >= MATCH_R:
            continue
        if d * (strike_x - ox) > d * (p["strike_x"] - ox) + RECEDE_TOL:
            continue                                 # 멀어졌다 = 다음 잡초다
        return p
    return None
